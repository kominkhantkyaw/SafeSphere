export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [language, setLanguageState] = useState<Language>(() => {
        const saved = localStorage.getItem('safesphere_language');
        return (saved === 'en' || saved === 'de' || saved === 'my') ? saved : 'en';
    });

    useEffect(() => {
        localStorage.setItem('safesphere_language', language);
    }, [language]);

    const setLanguage = (lang: Language) => {
        setLanguageState(lang);
    };

    const t = (key: string): string => {
        return translations[language][key as keyof typeof translations['en']] || key;
    };

    const translateDescription = (desc: string): string => {
        const key = DESC_KEYS[desc];
        return key ? t(key) : desc;
    };

    const translateReportType = (type: string): string => {
        const normalized = type?.toUpperCase()?.replace(/\s+/g, '_');
        const key = REPORT_TYPE_KEYS[normalized];
        return key ? t(key) : type;
    };

    const translateAlertTitle = (title: string): string => {
        const key = ALERT_TITLE_KEYS[title];
        return key ? t(key) : title;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, t, translateDescription, translateReportType, translateAlertTitle }}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useLanguage = () => {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
};
